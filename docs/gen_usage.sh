#!/bin/bash
# Regenerates docs/usage.md with the real output of every plugin on every sample in sample/work.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VOL="${VOL:-$ROOT/.venv/bin/vol}"
cd "$ROOT/sample/work"; mkdir -p .volcache
{
  echo "# Usage and real output"
  echo
  echo "Generated by \`docs/gen_usage.sh\` with Volatility 3 $("$VOL" --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1)"
  echo "on the samples of the release. Run from the folder that holds the image and the \`isf/\` directory."
  for elf in io-uring-*.elf; do
    k="${elf#io-uring-}"; k="${k%.elf}"
    echo; echo "## Kernel $k"
    for p in IoUring Sqes Cqes Registered; do
      echo; echo '```'
      echo "\$ vol -p plugins -f $elf -s isf linux.io_uring.$p"
      "$VOL" -q --cache-path "$ROOT/sample/work/.volcache" -p "$ROOT/plugins" -f "$elf" -s isf "linux.io_uring.$p" 2>/dev/null | sed '/^Volatility 3 Framework/d;/^$/d' | column -t -s $'\t'
      echo '```'
    done
  done
} > "$ROOT/docs/usage.md"
echo "wrote docs/usage.md"
